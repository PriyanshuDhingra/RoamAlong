"""Coverage report and hero-place candidates (§10.4 step 13, §16 Phase 0).

Per H3 res-8 cell: how many entities exist and how many have material to build story cards from. Cards don't
exist yet, so "has narrative source" (an English Wikipedia article) stands in for card coverage until
build_story_cards.py runs. Writes data/reports/coverage.md and data/reports/hero_candidates.csv.
"""

from __future__ import annotations

import csv
from collections import Counter, defaultdict

import h3

from pipeline.common import REPORTS, STAGING, bbox_from_env, read_jsonl

HERO_KINDS = {"building", "venue", "artwork", "monument", "park", "area", "street", "river", "plaque"}
N_CANDIDATES = 45


def has_narrative(e: dict) -> bool:
    return bool(e["attrs"].get("wd", {}).get("enwiki"))


def has_heritage(e: dict) -> bool:
    return bool(e["attrs"].get("heritage") or e["attrs"].get("wd", {}).get("heritage") or e["attrs"].get("historic"))


def dims_available(e: dict) -> list[str]:
    """Rough guess at which story dimensions the structured data can already support."""
    a, wd = e["attrs"], e["attrs"].get("wd", {})
    dims = []
    if wd.get("inception") or a.get("start_date") or has_heritage(e):
        dims.append("history")
    if wd.get("architect") or wd.get("style") or a.get("architect") or a.get("building:architecture"):
        dims.append("architecture")
    if e["kind"] in ("artwork", "monument") or wd.get("creator"):
        dims.append("art")
    if e["kind"] in ("park", "river"):
        dims.append("nature")
    if wd.get("named_after"):
        dims.append("people")
    return dims


def main() -> None:
    ents = list(read_jsonl(STAGING / "entities.jsonl"))
    review = list(read_jsonl(STAGING / "link_review.jsonl"))
    bbox = bbox_from_env()

    cells: dict[str, list[dict]] = defaultdict(list)
    for e in ents:
        cells[h3.latlng_to_cell(e["lat"], e["lon"], 8)].append(e)

    candidates = sorted((e for e in ents if e["kind"] in HERO_KINDS and (e["wikidata_id"] or has_heritage(e))),
                        key=lambda e: -e["prominence_raw"])[:N_CANDIDATES]

    REPORTS.mkdir(parents=True, exist_ok=True)
    with (REPORTS / "hero_candidates.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["rank", "id", "name", "kind", "prominence_raw", "wikidata", "enwiki", "enwiki_len", "sitelinks",
                    "heritage", "architect", "inception", "dims_from_structured_data", "has_geometry", "lat", "lon"])
        for i, e in enumerate(candidates, 1):
            wd = e["attrs"].get("wd", {})
            w.writerow([i, e["id"], e["name"], e["kind"], e["prominence_raw"], e["wikidata_id"] or "",
                        wd.get("enwiki", ""), wd.get("enwiki_len", 0), wd.get("sitelinks", 0),
                        "yes" if has_heritage(e) else "", "; ".join(wd.get("architect", [])), wd.get("inception", ""),
                        " ".join(dims_available(e)), "yes" if e["geometry"] else "point only", e["lat"], e["lon"]])

    kinds = Counter(e["kind"] for e in ents)
    lines = [
        "# Demo-area coverage report",
        "",
        f"Bbox (s,w,n,e): `{bbox.overpass()}`. Generated by `pipeline/report.py` from `data/staging/entities.jsonl`.",
        "Re-run with `make data`.",
        "",
        "## Totals",
        "",
        f"- Entities: **{len(ents)}** ({', '.join(f'{k} {v}' for k, v in kinds.most_common())})",
        (f"- Linked to Wikidata: {sum(1 for e in ents if e['wikidata_id'])}"
        f" (of which Wikidata-only, no OSM geometry: {sum(1 for e in ents if e['wikidata_id'] and not e['osm_ids'])})"),
        f"- With an English Wikipedia article (narrative source for cards): {sum(1 for e in ents if has_narrative(e))}",
        f"- With heritage designation or historic tag: {sum(1 for e in ents if has_heritage(e))}",
        f"- Link decisions waiting for review: {len(review)} (`data/staging/link_review.jsonl`)",
        "",
        "## Per H3 res-8 cell",
        "",
        "| cell | entities | with Wikipedia | heritage | buildings | food | art & monuments |",
        "|---|---|---|---|---|---|---|",
    ]
    for cell, es in sorted(cells.items(), key=lambda kv: -len(kv[1])):
        lines.append(f"| `{cell}` | {len(es)} | {sum(map(has_narrative, es))} | {sum(map(has_heritage, es))} | "
                     f"{sum(e['kind'] == 'building' for e in es)} | {sum(e['kind'] == 'food' for e in es)} | "
                     f"{sum(e['kind'] in ('artwork', 'monument', 'plaque') for e in es)} |")
    lines += [
        "",
        f"## Hero-place candidates (top {N_CANDIDATES} by prominence)",
        "",
        "Pick 20–30 of these (§1.2). Full columns in `hero_candidates.csv`. *Point only* means no footprint yet:",
        "fix the OSM link (or add one to `pipeline/curated/link_overrides.json`) before using it as a hero place.",
        "",
        "| # | name | kind | Wikipedia | heritage | architect | built | dims from data | geometry |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for i, e in enumerate(candidates, 1):
        wd = e["attrs"].get("wd", {})
        lines.append(f"| {i} | {e['name']} | {e['kind']} | {'✓' if has_narrative(e) else ''} | "
                     f"{'✓' if has_heritage(e) else ''} | {', '.join(wd.get('architect', [])[:2])} | "
                     f"{wd.get('inception', '')} | {' '.join(dims_available(e))} | "
                     f"{'' if e['geometry'] else 'point only'} |")
    lines += [
        "",
        "## Known gaps",
        "",
        "- Wikipedia text, Toronto Open Data (heritage register, 3D massing, public art, street trees, neighbourhoods),",
        "  Wikivoyage and the curated geology layer (lost rivers, Lake Iroquois shoreline) are not ingested yet.",
        "- Prominence uses article length, sitelinks, heritage and height only; no curated boost yet.",
        "",
    ]
    (REPORTS / "coverage.md").write_text("\n".join(lines))
    print(f"wrote {REPORTS / 'coverage.md'} and hero_candidates.csv ({len(cells)} cells, {len(candidates)} candidates)")


if __name__ == "__main__":
    main()
